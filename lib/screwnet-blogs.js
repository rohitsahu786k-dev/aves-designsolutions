export function getBlogBySlug(slug) {
  if (!slug) return null;
  const clean = String(slug).trim().toLowerCase();
  return SCREWNET_BLOGS.find((b) => b.slug.toLowerCase() === clean) || null;
}

export function getBlogCategories() {
  const map = new Map();
  SCREWNET_BLOGS.forEach((b) => {
    const count = (map.get(b.category) || 0) + 1;
    map.set(b.category, count);
  });
  return [...map.entries()].map(([name, count]) => ({ name, count }));
}
